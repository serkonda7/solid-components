export const deviceColumns: DataTableColumn<Device>[] = [
	{ key: 'name', label: 'Name', sortable: true, toggleable: false },
	{ key: 'status', label: 'Status', sortable: true },
	{ key: 'role', label: 'Role', sortable: true },
	{ key: 'manufacturer', label: 'Manufacturer', sortable: true },
	{ key: 'model', label: 'Model', sortable: true, defaultVisible: false },
	{ key: 'site', label: 'Site', sortable: true },
	{
		key: 'rack',
		label: 'Rack',
		sortable: true,
		getValue: (device) =>
			device.rack ? `${device.rack}${device.position ? ` / U${device.position}` : ''}` : '—',
	},
	{ key: 'tenant', label: 'Tenant', sortable: true, getValue: (device) => device.tenant ?? '—' },
	{ key: 'platform', label: 'Platform', sortable: true, defaultVisible: false },
	{
		key: 'primaryIp',
		label: 'Primary IP',
		sortable: true,
		getValue: (device) => device.primaryIp ?? '—',
	},
	{ key: 'serial', label: 'Serial', defaultVisible: false },
	{ key: 'tags', label: 'Tags', defaultVisible: false, getValue: (d) => d.tags.join(', ') },
]

